--  08 · UPDATE · ปุ่ม UPDATE
--  แก้ค่าในแถวที่มีอยู่แล้ว (อย่าลืม WHERE ไม่งั้นแก้ทุกแถว!)
--  ในฉาก: ตะเกียงดวงที่ 2 ค่อย ๆ สว่างขึ้น พร้อมป้ายค่าก่อน → หลัง
-- =====================================================================

-- คำสั่งที่ปุ่ม UPDATE ใส่ให้
UPDATE lanterns
SET brightness = 1.0
WHERE id = 2;


-- ตัวอย่างเพิ่มเติม ----------------------------------------------------

-- เปลี่ยนสีหลังคา Lamplighter House
UPDATE buildings
SET roof_color = 'green'
WHERE id = 7;

-- Green Hall ไม่มีคนอยู่แล้ว → หน้าต่างดับ
UPDATE buildings
