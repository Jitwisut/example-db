-- =====================================================================
--  06 · GROUP BY · ปุ่ม GROUP BY
--  รวมแถวที่มีค่าเหมือนกันเป็นกลุ่ม แล้วนับด้วย COUNT(*)
--  ในฉาก: อาคารมีจุดสีตามกลุ่ม และตัวเลขลอยเหนือกลุ่มคือ COUNT
-- =====================================================================

-- คำสั่งที่ปุ่ม GROUP BY ใส่ให้: สีหลังคาแต่ละสีมีกี่หลัง
SELECT roof_color, COUNT(*)
FROM buildings
GROUP BY roof_color;


-- ตัวอย่างเพิ่มเติม ----------------------------------------------------

-- แต่ละเกาะมีอาคารกี่หลัง
SELECT island_id, COUNT(*)
FROM buildings
GROUP BY island_id;

-- อาคารแต่ละประเภทมีกี่หลัง
SELECT type, COUNT(*)
FROM buildings
GROUP BY type;
